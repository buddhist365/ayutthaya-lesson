(function () {
  const page = decodeURIComponent(location.pathname.split("/").pop()) || "index.html";
  const x = LESSON_EXTRAS[page];
  const main = document.querySelector("main");
  if (!x || !main) return;

  // เป้าหมายของบท (ต่อจากวิดีโอ)
  const goals = document.createElement("section");
  goals.className = "goals";
  goals.innerHTML = `<h3 class="box-title">เมื่อเรียนจบบทนี้ นักเรียนจะ</h3>
    <ol>${x.goals.map(g => `<li>${g}</li>`).join("")}</ol>`;
  const video = main.querySelector("[data-video]");
  (video ? video.after(goals) : main.prepend(goals));

  // คำศัพท์ + สรุป (ก่อนคำถามตรวจสอบความเข้าใจ)
  const wrap = document.createElement("div");
  wrap.className = "lesson-end";
  wrap.innerHTML = `
    <section class="vocab">
      <h3 class="box-title">คำศัพท์สำคัญ <small>กดที่คำเพื่อดูความหมาย</small></h3>
      <div class="vocab-list">${x.vocab.map(([w, d], i) => `
        <button type="button" class="vocab-chip" aria-expanded="false" aria-controls="vd${i}">${w}</button>`).join("")}
      </div>
      ${x.vocab.map(([w, d], i) => `<p class="vocab-def" id="vd${i}" hidden><b>${w}</b> ${d}</p>`).join("")}
    </section>
    <section class="summary">
      <h3 class="box-title">สรุปสาระสำคัญ</h3>
      <ul>${x.summary.map(s => `<li>${s}</li>`).join("")}</ul>
    </section>`;
  const check = main.querySelector("details.check");
  (check ? check.before(wrap) : main.append(wrap));

  wrap.querySelectorAll(".vocab-chip").forEach(b => b.addEventListener("click", () => {
    const def = document.getElementById(b.getAttribute("aria-controls"));
    const open = b.getAttribute("aria-expanded") !== "true";
    wrap.querySelectorAll(".vocab-chip").forEach(o => o.setAttribute("aria-expanded", "false"));
    wrap.querySelectorAll(".vocab-def").forEach(d => d.hidden = true);
    b.setAttribute("aria-expanded", open);
    def.hidden = !open;
  }));
})();
